    UPDATE SERVER_MEMBERS
       SET SERVER_ROLE = P_SERVER_ROLE
     WHERE SERVER_ID = P_SERVER_ID
       AND USER_ID = P_MEMBER_USER_ID;
  END UPDATE_MEMBER_ROLE;
END MESSAGEME_COMMUNITY_API;
