    IF NOT CAN_MANAGE_SERVER(
      P_ACTOR_USER_ID,
      P_ACTOR_APP_ROLE,
      L_CONTEXT.OWNER_ID,
      L_CONTEXT.SERVER_ROLE
    ) THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(403, 'Only server admins can remove members.');
    END IF;

    IF P_MEMBER_USER_ID = P_ACTOR_USER_ID THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(400, 'Use another admin account before removing yourself.');
    END IF;

    IF P_MEMBER_USER_ID = L_CONTEXT.OWNER_ID THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(403, 'The server owner cannot be removed.');
    END IF;

    SELECT COUNT(*)
      INTO L_COUNT
      FROM SERVER_MEMBERS
     WHERE SERVER_ID = P_SERVER_ID
       AND USER_ID = P_MEMBER_USER_ID;

    IF L_COUNT = 0 THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(404, 'That user is not a member of this server.');
    END IF;

    REMOVE_SERVER_MEMBERSHIP_DATA(P_SERVER_ID, P_MEMBER_USER_ID);
  END REMOVE_MEMBER;

