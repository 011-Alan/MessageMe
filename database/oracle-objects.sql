  PROCEDURE ENSURE_UNIQUE_SERVER_NAME(
    P_SERVER_NAME IN VARCHAR2,
    P_EXCLUDED_SERVER_ID IN NUMBER DEFAULT NULL
  ) AS
    L_COUNT NUMBER;
  BEGIN
    SELECT COUNT(*)
      INTO L_COUNT
      FROM SERVERS
     WHERE LOWER(SERVER_NAME) = LOWER(P_SERVER_NAME)
       AND (P_EXCLUDED_SERVER_ID IS NULL OR SERVER_ID <> P_EXCLUDED_SERVER_ID);

    IF L_COUNT > 0 THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(409, 'Server names must be unique.');
    END IF;
  END ENSURE_UNIQUE_SERVER_NAME;

  PROCEDURE ENSURE_UNIQUE_CHANNEL_NAME(
    P_SERVER_ID IN NUMBER,
    P_CHANNEL_NAME IN VARCHAR2,
    P_EXCLUDED_CHANNEL_ID IN NUMBER DEFAULT NULL
  ) AS
    L_COUNT NUMBER;
  BEGIN
    SELECT COUNT(*)
      INTO L_COUNT
      FROM CHANNELS
     WHERE SERVER_ID = P_SERVER_ID
       AND LOWER(CHANNEL_NAME) = LOWER(P_CHANNEL_NAME)
       AND (P_EXCLUDED_CHANNEL_ID IS NULL OR CHANNEL_ID <> P_EXCLUDED_CHANNEL_ID);

    IF L_COUNT > 0 THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(
        409,
        'Channel names must be unique inside a server.'
      );
    END IF;
  END ENSURE_UNIQUE_CHANNEL_NAME;

  PROCEDURE DELETE_CHANNEL_DATA(
    P_CHANNEL_ID IN NUMBER
  ) AS
  BEGIN
    DELETE FROM ATTACHMENTS
     WHERE MESSAGE_ID IN (
       SELECT MESSAGE_ID
         FROM MESSAGES
        WHERE CHANNEL_ID = P_CHANNEL_ID
     );

    DELETE FROM CHANNEL_READ_STATE
     WHERE CHANNEL_ID = P_CHANNEL_ID;

    DELETE FROM MESSAGES
     WHERE CHANNEL_ID = P_CHANNEL_ID;

    DELETE FROM CHANNELS
     WHERE CHANNEL_ID = P_CHANNEL_ID;
  END DELETE_CHANNEL_DATA;

  PROCEDURE DELETE_SERVER_DATA(
    P_SERVER_ID IN NUMBER
  ) AS
  BEGIN
    DELETE FROM ATTACHMENTS
     WHERE MESSAGE_ID IN (
       SELECT M.MESSAGE_ID
         FROM MESSAGES M
         JOIN CHANNELS C
           ON C.CHANNEL_ID = M.CHANNEL_ID
        WHERE C.SERVER_ID = P_SERVER_ID
     );

    DELETE FROM CHANNEL_READ_STATE
     WHERE CHANNEL_ID IN (
       SELECT CHANNEL_ID
         FROM CHANNELS
        WHERE SERVER_ID = P_SERVER_ID
     );

    DELETE FROM MESSAGES
     WHERE CHANNEL_ID IN (
       SELECT CHANNEL_ID
         FROM CHANNELS
        WHERE SERVER_ID = P_SERVER_ID
     );

    DELETE FROM CHANNELS
     WHERE SERVER_ID = P_SERVER_ID;

    DELETE FROM SERVER_JOIN_REQUESTS
     WHERE SERVER_ID = P_SERVER_ID;

    DELETE FROM SERVER_MEMBERS
     WHERE SERVER_ID = P_SERVER_ID;

    DELETE FROM SERVERS
     WHERE SERVER_ID = P_SERVER_ID;
  END DELETE_SERVER_DATA;

  PROCEDURE REMOVE_SERVER_MEMBERSHIP_DATA(
    P_SERVER_ID IN NUMBER,
    P_USER_ID IN NUMBER
  ) AS
  BEGIN
    DELETE FROM CHANNEL_READ_STATE
     WHERE USER_ID = P_USER_ID
       AND CHANNEL_ID IN (
         SELECT CHANNEL_ID
           FROM CHANNELS
          WHERE SERVER_ID = P_SERVER_ID
       );

    DELETE FROM SERVER_JOIN_REQUESTS
     WHERE SERVER_ID = P_SERVER_ID
       AND USER_ID = P_USER_ID;

    DELETE FROM SERVER_MEMBERS
     WHERE SERVER_ID = P_SERVER_ID
       AND USER_ID = P_USER_ID;
  END REMOVE_SERVER_MEMBERSHIP_DATA;

