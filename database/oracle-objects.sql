CREATE OR REPLACE TRIGGER MESSAGEME_MESSAGE_AUDIT_TRG
AFTER UPDATE OF MESSAGE_TEXT, MESSAGE_TYPE, IS_DELETED, EDITED_AT, DELETED_AT, DELETED_BY ON MESSAGES
FOR EACH ROW
BEGIN
  INSERT INTO MESSAGE_AUDIT_LOG (
    MESSAGE_ID,
    ACTION_TYPE,
    ACTION_AT,
    OLD_MESSAGE_TEXT,
    NEW_MESSAGE_TEXT,
    OLD_MESSAGE_TYPE,
    NEW_MESSAGE_TYPE,
    OLD_IS_DELETED,
    NEW_IS_DELETED
  ) VALUES (
    :NEW.MESSAGE_ID,
    CASE
      WHEN NVL(:OLD.IS_DELETED, 0) = 0 AND NVL(:NEW.IS_DELETED, 0) = 1 THEN 'DELETE'
      ELSE 'EDIT'
    END,
    SYSTIMESTAMP,
    :OLD.MESSAGE_TEXT,
    :NEW.MESSAGE_TEXT,
    :OLD.MESSAGE_TYPE,
    :NEW.MESSAGE_TYPE,
    :OLD.IS_DELETED,
    :NEW.IS_DELETED
  );
END;
