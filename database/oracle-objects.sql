  END DELETE_SERVER;

  PROCEDURE LEAVE_SERVER(
    P_SERVER_ID IN NUMBER,
    P_ACTOR_USER_ID IN NUMBER,
    P_DELETED_SERVER OUT NUMBER,
    P_TRANSFERRED_OWNERSHIP OUT NUMBER,
    P_NEW_OWNER_USER_ID OUT NUMBER
  ) AS
    L_CONTEXT T_SERVER_CONTEXT;
    L_NEXT_OWNER_USER_ID SERVER_MEMBERS.USER_ID%TYPE;
    L_NEXT_OWNER_ROLE SERVER_MEMBERS.SERVER_ROLE%TYPE;
  BEGIN
    P_DELETED_SERVER := 0;
    P_TRANSFERRED_OWNERSHIP := 0;
    P_NEW_OWNER_USER_ID := NULL;

    L_CONTEXT := REQUIRE_SERVER_CONTEXT(P_SERVER_ID, P_ACTOR_USER_ID);

    IF L_CONTEXT.OWNER_ID <> P_ACTOR_USER_ID THEN
      REMOVE_SERVER_MEMBERSHIP_DATA(P_SERVER_ID, P_ACTOR_USER_ID);
      RETURN;
    END IF;

    BEGIN
      SELECT USER_ID,
             SERVER_ROLE
        INTO L_NEXT_OWNER_USER_ID,
             L_NEXT_OWNER_ROLE
        FROM (
          SELECT USER_ID,
                 SERVER_ROLE
            FROM SERVER_MEMBERS
           WHERE SERVER_ID = P_SERVER_ID
             AND USER_ID <> P_ACTOR_USER_ID
           ORDER BY CASE SERVER_ROLE WHEN 'ADMIN' THEN 0 ELSE 1 END,
                    JOIN_DATE,
                    USER_ID
        )
       WHERE ROWNUM = 1;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        DELETE_SERVER_DATA(P_SERVER_ID);
        P_DELETED_SERVER := 1;
        RETURN;
    END;

    UPDATE SERVERS
       SET OWNER_ID = L_NEXT_OWNER_USER_ID
     WHERE SERVER_ID = P_SERVER_ID;

    IF L_NEXT_OWNER_ROLE <> 'ADMIN' THEN
      UPDATE SERVER_MEMBERS
         SET SERVER_ROLE = 'ADMIN'
       WHERE SERVER_ID = P_SERVER_ID
         AND USER_ID = L_NEXT_OWNER_USER_ID;
    END IF;

    REMOVE_SERVER_MEMBERSHIP_DATA(P_SERVER_ID, P_ACTOR_USER_ID);

    P_TRANSFERRED_OWNERSHIP := 1;
    P_NEW_OWNER_USER_ID := L_NEXT_OWNER_USER_ID;
  END LEAVE_SERVER;

