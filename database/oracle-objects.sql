     WHERE SERVER_ID = P_SERVER_ID
       AND USER_ID = P_MEMBER_USER_ID;

    IF L_COUNT = 0 THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(404, 'That member was not found in this server.');
