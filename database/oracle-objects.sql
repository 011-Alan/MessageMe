CREATE OR REPLACE PACKAGE BODY MESSAGEME_ERROR_API AS
  PROCEDURE RAISE_HTTP(
    P_STATUS IN NUMBER,
    P_MESSAGE IN VARCHAR2
  ) AS
    L_ERROR_CODE NUMBER;
  BEGIN
    L_ERROR_CODE :=
      CASE
        WHEN TRUNC(P_STATUS) BETWEEN 400 AND 599 THEN -(20000 + TRUNC(P_STATUS))
        ELSE -20500
      END;

    RAISE_APPLICATION_ERROR(L_ERROR_CODE, P_MESSAGE, TRUE);
  END RAISE_HTTP;
END MESSAGEME_ERROR_API;
