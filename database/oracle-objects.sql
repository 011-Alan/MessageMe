CREATE OR REPLACE PACKAGE BODY MESSAGEME_MESSAGE_API AS
  TYPE T_MESSAGE_CONTEXT IS RECORD (
    MESSAGE_ID MESSAGES.MESSAGE_ID%TYPE,
    CHANNEL_ID MESSAGES.CHANNEL_ID%TYPE,
    AUTHOR_USER_ID MESSAGES.USER_ID%TYPE,
    IS_DELETED MESSAGES.IS_DELETED%TYPE,
    OWNER_ID SERVERS.OWNER_ID%TYPE,
    SERVER_ROLE SERVER_MEMBERS.SERVER_ROLE%TYPE
  );

  FUNCTION CAN_MODERATE_MESSAGE(
    P_ACTOR_USER_ID IN NUMBER,
    P_ACTOR_APP_ROLE IN VARCHAR2,
    P_OWNER_ID IN NUMBER,
    P_SERVER_ROLE IN VARCHAR2
  ) RETURN BOOLEAN AS
  BEGIN
    RETURN NVL(P_ACTOR_APP_ROLE, 'USER') = 'ADMIN'
      OR P_OWNER_ID = P_ACTOR_USER_ID
      OR NVL(P_SERVER_ROLE, 'MEMBER') = 'ADMIN';
  END CAN_MODERATE_MESSAGE;

  PROCEDURE ENSURE_CHANNEL_MEMBERSHIP(
    P_CHANNEL_ID IN NUMBER,
    P_ACTOR_USER_ID IN NUMBER
  ) AS
    L_COUNT NUMBER;
  BEGIN
    SELECT COUNT(*)
      INTO L_COUNT
      FROM CHANNELS C
      JOIN SERVERS S
        ON S.SERVER_ID = C.SERVER_ID
      JOIN SERVER_MEMBERS SM
        ON SM.SERVER_ID = S.SERVER_ID
     WHERE C.CHANNEL_ID = P_CHANNEL_ID
       AND SM.USER_ID = P_ACTOR_USER_ID;

    IF L_COUNT = 0 THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(403, 'You do not have access to that channel.');
    END IF;
  END ENSURE_CHANNEL_MEMBERSHIP;

  FUNCTION REQUIRE_MESSAGE_CONTEXT(
    P_MESSAGE_ID IN NUMBER,
    P_ACTOR_USER_ID IN NUMBER
  ) RETURN T_MESSAGE_CONTEXT AS
    L_CONTEXT T_MESSAGE_CONTEXT;
  BEGIN
    SELECT M.MESSAGE_ID,
           M.CHANNEL_ID,
           M.USER_ID,
           M.IS_DELETED,
           S.OWNER_ID,
           SM.SERVER_ROLE
      INTO L_CONTEXT
      FROM MESSAGES M
      JOIN CHANNELS C
        ON C.CHANNEL_ID = M.CHANNEL_ID
      JOIN SERVERS S
        ON S.SERVER_ID = C.SERVER_ID
      JOIN SERVER_MEMBERS SM
        ON SM.SERVER_ID = S.SERVER_ID
     WHERE M.MESSAGE_ID = P_MESSAGE_ID
       AND SM.USER_ID = P_ACTOR_USER_ID;

    RETURN L_CONTEXT;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(404, 'Message not found or you do not have access to it.');
  END REQUIRE_MESSAGE_CONTEXT;

  PROCEDURE UPSERT_READ_STATE(
    P_CHANNEL_ID IN NUMBER,
    P_USER_ID IN NUMBER,
    P_LAST_READ_MESSAGE_ID IN NUMBER
  ) AS
  BEGIN
    IF P_LAST_READ_MESSAGE_ID IS NULL THEN
      RETURN;
    END IF;

    MERGE INTO CHANNEL_READ_STATE TARGET
    USING (
      SELECT P_CHANNEL_ID AS CHANNEL_ID,
             P_USER_ID AS USER_ID,
             P_LAST_READ_MESSAGE_ID AS LAST_READ_MESSAGE_ID
        FROM DUAL
    ) SOURCE
       ON (
         TARGET.CHANNEL_ID = SOURCE.CHANNEL_ID
         AND TARGET.USER_ID = SOURCE.USER_ID
       )
     WHEN MATCHED THEN
       UPDATE
          SET TARGET.LAST_READ_MESSAGE_ID = SOURCE.LAST_READ_MESSAGE_ID,
              TARGET.LAST_READ_AT = SYSTIMESTAMP
     WHEN NOT MATCHED THEN
       INSERT (
         CHANNEL_ID,
         USER_ID,
         LAST_READ_MESSAGE_ID,
         LAST_READ_AT
       ) VALUES (
         SOURCE.CHANNEL_ID,
         SOURCE.USER_ID,
         SOURCE.LAST_READ_MESSAGE_ID,
         SYSTIMESTAMP
       );
  END UPSERT_READ_STATE;

  PROCEDURE CREATE_MESSAGE(
    P_CHANNEL_ID IN NUMBER,
    P_ACTOR_USER_ID IN NUMBER,
    P_MESSAGE_TEXT IN CLOB,
    P_MESSAGE_TYPE IN VARCHAR2,
    P_MESSAGE_ID OUT NUMBER
  ) AS
  BEGIN
    ENSURE_CHANNEL_MEMBERSHIP(P_CHANNEL_ID, P_ACTOR_USER_ID);

    INSERT INTO MESSAGES (
      CHANNEL_ID,
      USER_ID,
      MESSAGE_TEXT,
      MESSAGE_TYPE,
      IS_DELETED
    ) VALUES (
      P_CHANNEL_ID,
      P_ACTOR_USER_ID,
      P_MESSAGE_TEXT,
      P_MESSAGE_TYPE,
      0
    )
    RETURNING MESSAGE_ID INTO P_MESSAGE_ID;
  END CREATE_MESSAGE;

  PROCEDURE ADD_ATTACHMENT(
    P_MESSAGE_ID IN NUMBER,
    P_FILE_NAME IN VARCHAR2,
    P_FILE_URL IN VARCHAR2,
    P_FILE_TYPE IN VARCHAR2,
    P_MIME_TYPE IN VARCHAR2,
    P_FILE_SIZE IN NUMBER
  ) AS
  BEGIN
    INSERT INTO ATTACHMENTS (
      MESSAGE_ID,
      FILE_NAME,
      FILE_URL,
      FILE_TYPE,
      MIME_TYPE,
      FILE_SIZE
    ) VALUES (
      P_MESSAGE_ID,
      P_FILE_NAME,
      P_FILE_URL,
      P_FILE_TYPE,
      P_MIME_TYPE,
      P_FILE_SIZE
    );
  END ADD_ATTACHMENT;

  PROCEDURE DELETE_ATTACHMENT(
    P_ATTACHMENT_ID IN NUMBER,
    P_MESSAGE_ID IN NUMBER
  ) AS
  BEGIN
    DELETE FROM ATTACHMENTS
     WHERE ATTACHMENT_ID = P_ATTACHMENT_ID
       AND MESSAGE_ID = P_MESSAGE_ID;
  END DELETE_ATTACHMENT;

  PROCEDURE UPDATE_MESSAGE_BODY(
    P_MESSAGE_ID IN NUMBER,
    P_ACTOR_USER_ID IN NUMBER,
    P_ACTOR_APP_ROLE IN VARCHAR2,
    P_MESSAGE_TEXT IN CLOB,
    P_MESSAGE_TYPE IN VARCHAR2
  ) AS
    L_CONTEXT T_MESSAGE_CONTEXT;
  BEGIN
    L_CONTEXT := REQUIRE_MESSAGE_CONTEXT(P_MESSAGE_ID, P_ACTOR_USER_ID);

    IF NVL(L_CONTEXT.IS_DELETED, 0) = 1 THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(400, 'Deleted messages cannot be edited.');
    END IF;

    IF L_CONTEXT.AUTHOR_USER_ID <> P_ACTOR_USER_ID
       AND NOT CAN_MODERATE_MESSAGE(
         P_ACTOR_USER_ID,
         P_ACTOR_APP_ROLE,
         L_CONTEXT.OWNER_ID,
         L_CONTEXT.SERVER_ROLE
       ) THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(
        403,
        'Only the author or a server admin can edit this message.'
      );
    END IF;

    UPDATE MESSAGES
       SET MESSAGE_TEXT = P_MESSAGE_TEXT,
           MESSAGE_TYPE = P_MESSAGE_TYPE,
           EDITED_AT = SYSTIMESTAMP
     WHERE MESSAGE_ID = P_MESSAGE_ID;
  END UPDATE_MESSAGE_BODY;

  PROCEDURE SOFT_DELETE_MESSAGE(
    P_MESSAGE_ID IN NUMBER,
    P_ACTOR_USER_ID IN NUMBER,
    P_ACTOR_APP_ROLE IN VARCHAR2
  ) AS
    L_CONTEXT T_MESSAGE_CONTEXT;
  BEGIN
    L_CONTEXT := REQUIRE_MESSAGE_CONTEXT(P_MESSAGE_ID, P_ACTOR_USER_ID);

    IF L_CONTEXT.AUTHOR_USER_ID <> P_ACTOR_USER_ID
       AND NOT CAN_MODERATE_MESSAGE(
         P_ACTOR_USER_ID,
         P_ACTOR_APP_ROLE,
         L_CONTEXT.OWNER_ID,
         L_CONTEXT.SERVER_ROLE
       ) THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(
        403,
        'Only the author or a server admin can delete this message.'
      );
    END IF;

    UPDATE MESSAGES
       SET IS_DELETED = 1,
           MESSAGE_TEXT = NULL,
           MESSAGE_TYPE = 'TEXT',
           DELETED_AT = SYSTIMESTAMP,
           DELETED_BY = P_ACTOR_USER_ID,
           EDITED_AT = NULL
     WHERE MESSAGE_ID = P_MESSAGE_ID;

    DELETE FROM ATTACHMENTS
     WHERE MESSAGE_ID = P_MESSAGE_ID;
  END SOFT_DELETE_MESSAGE;
END MESSAGEME_MESSAGE_API;
/

