CREATE OR REPLACE PACKAGE BODY MESSAGEME_AUTH_API AS
  FUNCTION USERS_HAVE_LEGACY_PASSWORD RETURN BOOLEAN AS
    L_COUNT NUMBER;
  BEGIN
    SELECT COUNT(*)
      INTO L_COUNT
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'USERS'
       AND COLUMN_NAME = 'PASSWORD';

    RETURN L_COUNT > 0;
  END USERS_HAVE_LEGACY_PASSWORD;

  PROCEDURE REGISTER_USER(
    P_USERNAME IN VARCHAR2,
    P_EMAIL IN VARCHAR2,
    P_PASSWORD_HASH IN VARCHAR2,
    P_DISPLAY_NAME IN VARCHAR2,
    P_AVATAR_COLOR IN VARCHAR2,
    P_LEGACY_PASSWORD IN VARCHAR2,
    P_USER_ID OUT NUMBER,
    P_APP_ROLE OUT VARCHAR2
  ) AS
    L_TOTAL_USERS NUMBER;
    L_DISPLAY_NAME USERS.DISPLAY_NAME%TYPE := NVL(NULLIF(TRIM(P_DISPLAY_NAME), ''), P_USERNAME);
    L_AVATAR_COLOR USERS.AVATAR_COLOR%TYPE := NVL(NULLIF(TRIM(P_AVATAR_COLOR), ''), '#7C5CFF');
    L_DUPLICATE_COUNT NUMBER;
  BEGIN
    SELECT COUNT(*)
      INTO L_DUPLICATE_COUNT
      FROM USERS
     WHERE LOWER(USERNAME) = LOWER(P_USERNAME);

    IF L_DUPLICATE_COUNT > 0 THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(409, 'That username is already taken.');
    END IF;

    SELECT COUNT(*)
      INTO L_DUPLICATE_COUNT
      FROM USERS
     WHERE LOWER(EMAIL) = LOWER(P_EMAIL);

    IF L_DUPLICATE_COUNT > 0 THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(409, 'That email address is already registered.');
    END IF;

    SELECT COUNT(*)
      INTO L_TOTAL_USERS
      FROM USERS;

    P_APP_ROLE := CASE WHEN L_TOTAL_USERS = 0 THEN 'ADMIN' ELSE 'USER' END;

    IF USERS_HAVE_LEGACY_PASSWORD THEN
      EXECUTE IMMEDIATE
        'INSERT INTO USERS (
           USERNAME,
           EMAIL,
           PASSWORD,
           PASSWORD_HASH,
           DISPLAY_NAME,
           APP_ROLE,
           AVATAR_COLOR
         ) VALUES (
           :1,
           :2,
           :3,
           :4,
           :5,
           :6,
           :7
         )
         RETURNING USER_ID INTO :8'
        USING
          P_USERNAME,
          P_EMAIL,
          NVL(P_LEGACY_PASSWORD, P_PASSWORD_HASH),
          P_PASSWORD_HASH,
          L_DISPLAY_NAME,
          P_APP_ROLE,
          L_AVATAR_COLOR,
          OUT P_USER_ID;
    ELSE
      INSERT INTO USERS (
        USERNAME,
        EMAIL,
        PASSWORD_HASH,
        DISPLAY_NAME,
        APP_ROLE,
        AVATAR_COLOR
      ) VALUES (
        P_USERNAME,
        P_EMAIL,
        P_PASSWORD_HASH,
        L_DISPLAY_NAME,
        P_APP_ROLE,
        L_AVATAR_COLOR
      )
      RETURNING USER_ID INTO P_USER_ID;
    END IF;
  END REGISTER_USER;

