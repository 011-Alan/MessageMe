BEFORE INSERT OR UPDATE ON USERS
FOR EACH ROW
BEGIN
  IF :NEW.DISPLAY_NAME IS NULL OR TRIM(:NEW.DISPLAY_NAME) IS NULL THEN
    :NEW.DISPLAY_NAME := :NEW.USERNAME;
  END IF;

  IF :NEW.APP_ROLE IS NULL THEN
    :NEW.APP_ROLE := 'USER';
  END IF;

  IF :NEW.AVATAR_COLOR IS NULL THEN
    :NEW.AVATAR_COLOR := '#7C5CFF';
  END IF;
END;
