  PROCEDURE CREATE_JOIN_REQUEST(
    P_SERVER_ID IN NUMBER,
    P_ACTOR_USER_ID IN NUMBER,
    P_REQUEST_MESSAGE IN VARCHAR2
  ) AS
    L_COUNT NUMBER;
  BEGIN
    SELECT COUNT(*)
      INTO L_COUNT
      FROM SERVERS
     WHERE SERVER_ID = P_SERVER_ID;

    IF L_COUNT = 0 THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(404, 'That server does not exist.');
    END IF;

    SELECT COUNT(*)
      INTO L_COUNT
      FROM SERVER_MEMBERS
     WHERE SERVER_ID = P_SERVER_ID
       AND USER_ID = P_ACTOR_USER_ID;

    IF L_COUNT > 0 THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(400, 'You are already a member of this server.');
    END IF;

    SELECT COUNT(*)
      INTO L_COUNT
      FROM SERVER_JOIN_REQUESTS
     WHERE SERVER_ID = P_SERVER_ID
       AND USER_ID = P_ACTOR_USER_ID
       AND STATUS = 'PENDING';

    IF L_COUNT > 0 THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(
        409,
        'You already have a pending request for this server.'
      );
    END IF;

    INSERT INTO SERVER_JOIN_REQUESTS (
      SERVER_ID,
      USER_ID,
      REQUEST_MESSAGE,
      STATUS
    ) VALUES (
      P_SERVER_ID,
      P_ACTOR_USER_ID,
      P_REQUEST_MESSAGE,
      'PENDING'
    );
  END CREATE_JOIN_REQUEST;

  PROCEDURE REVIEW_JOIN_REQUEST(
    P_REQUEST_ID IN NUMBER,
    P_ACTOR_USER_ID IN NUMBER,
    P_ACTOR_APP_ROLE IN VARCHAR2,
    P_STATUS IN VARCHAR2
  ) AS
    L_SERVER_ID SERVER_JOIN_REQUESTS.SERVER_ID%TYPE;
    L_REQUEST_USER_ID SERVER_JOIN_REQUESTS.USER_ID%TYPE;
    L_STATUS SERVER_JOIN_REQUESTS.STATUS%TYPE;
    L_CONTEXT T_SERVER_CONTEXT;
    L_COUNT NUMBER;
  BEGIN
    BEGIN
      SELECT SERVER_ID,
             USER_ID,
             STATUS
        INTO L_SERVER_ID,
             L_REQUEST_USER_ID,
             L_STATUS
        FROM SERVER_JOIN_REQUESTS
       WHERE REQUEST_ID = P_REQUEST_ID;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        MESSAGEME_ERROR_API.RAISE_HTTP(404, 'Join request not found.');
    END;

    IF L_STATUS <> 'PENDING' THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(400, 'This request has already been reviewed.');
    END IF;

    L_CONTEXT := REQUIRE_SERVER_CONTEXT(L_SERVER_ID, P_ACTOR_USER_ID);

    IF NOT CAN_MANAGE_SERVER(
      P_ACTOR_USER_ID,
      P_ACTOR_APP_ROLE,
      L_CONTEXT.OWNER_ID,
      L_CONTEXT.SERVER_ROLE
    ) THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(403, 'Only server admins can review join requests.');
    END IF;

    UPDATE SERVER_JOIN_REQUESTS
       SET STATUS = P_STATUS,
           REVIEWED_BY = P_ACTOR_USER_ID,
           REVIEWED_AT = SYSTIMESTAMP
     WHERE REQUEST_ID = P_REQUEST_ID;

    IF P_STATUS = 'APPROVED' THEN
      SELECT COUNT(*)
        INTO L_COUNT
        FROM SERVER_MEMBERS
       WHERE SERVER_ID = L_SERVER_ID
         AND USER_ID = L_REQUEST_USER_ID;

      IF L_COUNT = 0 THEN
        INSERT INTO SERVER_MEMBERS (
          SERVER_ID,
          USER_ID,
          SERVER_ROLE
        ) VALUES (
          L_SERVER_ID,
          L_REQUEST_USER_ID,
          'MEMBER'
        );
      END IF;
    END IF;
  END REVIEW_JOIN_REQUEST;

  PROCEDURE ADD_MEMBER(
    P_SERVER_ID IN NUMBER,
    P_ACTOR_USER_ID IN NUMBER,
    P_ACTOR_APP_ROLE IN VARCHAR2,
    P_MEMBER_USER_ID IN NUMBER,
    P_SERVER_ROLE IN VARCHAR2
  ) AS
    L_CONTEXT T_SERVER_CONTEXT;
    L_COUNT NUMBER;
  BEGIN
    L_CONTEXT := REQUIRE_SERVER_CONTEXT(P_SERVER_ID, P_ACTOR_USER_ID);

    IF NOT CAN_ADD_MEMBERS(
      P_ACTOR_USER_ID,
      L_CONTEXT.OWNER_ID,
      L_CONTEXT.SERVER_ROLE
    ) THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(403, 'Only server owners or admins can add members.');
    END IF;

    SELECT COUNT(*)
      INTO L_COUNT
      FROM USERS
     WHERE USER_ID = P_MEMBER_USER_ID;

    IF L_COUNT = 0 THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(404, 'That user was not found.');
    END IF;

    SELECT COUNT(*)
      INTO L_COUNT
      FROM SERVER_MEMBERS
     WHERE SERVER_ID = P_SERVER_ID
       AND USER_ID = P_MEMBER_USER_ID;

    IF L_COUNT > 0 THEN
      MESSAGEME_ERROR_API.RAISE_HTTP(409, 'That user is already a member of this server.');
    END IF;

    INSERT INTO SERVER_MEMBERS (
      SERVER_ID,
      USER_ID,
      SERVER_ROLE
    ) VALUES (
      P_SERVER_ID,
      P_MEMBER_USER_ID,
      P_SERVER_ROLE
    );

    DELETE FROM SERVER_JOIN_REQUESTS
     WHERE SERVER_ID = P_SERVER_ID
       AND USER_ID = P_MEMBER_USER_ID
       AND STATUS = 'PENDING';
  END ADD_MEMBER;

  PROCEDURE REMOVE_MEMBER(
    P_SERVER_ID IN NUMBER,
    P_ACTOR_USER_ID IN NUMBER,
    P_ACTOR_APP_ROLE IN VARCHAR2,
    P_MEMBER_USER_ID IN NUMBER
  ) AS
    L_CONTEXT T_SERVER_CONTEXT;
    L_COUNT NUMBER;
  BEGIN
