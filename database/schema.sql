CREATE TABLE USERS (
  USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USERNAME VARCHAR2(50) NOT NULL UNIQUE,
  EMAIL VARCHAR2(120) NOT NULL UNIQUE,
  PASSWORD_HASH VARCHAR2(300) NOT NULL,
  DISPLAY_NAME VARCHAR2(80) NOT NULL,
  APP_ROLE VARCHAR2(10) DEFAULT 'USER' NOT NULL
    CHECK (APP_ROLE IN ('ADMIN', 'USER')),
  AVATAR_COLOR VARCHAR2(20) DEFAULT '#7C5CFF' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE SERVERS (
  SERVER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SERVER_NAME VARCHAR2(100) NOT NULL UNIQUE,
  DESCRIPTION VARCHAR2(300),
  OWNER_ID NUMBER NOT NULL,
  IS_PRIVATE NUMBER(1) DEFAULT 0 NOT NULL
    CHECK (IS_PRIVATE IN (0, 1)),
  INVITE_CODE VARCHAR2(24) NOT NULL UNIQUE,
  ACCENT_COLOR VARCHAR2(20) DEFAULT '#7C5CFF' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_SERVERS_OWNER
    FOREIGN KEY (OWNER_ID) REFERENCES USERS (USER_ID)
);

CREATE TABLE USER_SESSIONS (
  SESSION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_ID NUMBER NOT NULL,
  SESSION_TOKEN VARCHAR2(128) NOT NULL UNIQUE,
  LOGIN_TIME TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  EXPIRES_AT TIMESTAMP NOT NULL,
  LAST_ACTIVE_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  LOGOUT_TIME TIMESTAMP,
  USER_AGENT VARCHAR2(255),
  CONSTRAINT FK_SESSIONS_USER
    FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID) ON DELETE CASCADE
);

CREATE TABLE SERVER_MEMBERS (
  SERVER_ID NUMBER NOT NULL,
  USER_ID NUMBER NOT NULL,
  SERVER_ROLE VARCHAR2(10) DEFAULT 'MEMBER' NOT NULL
    CHECK (SERVER_ROLE IN ('ADMIN', 'MEMBER')),
  JOIN_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_SERVER_MEMBERS PRIMARY KEY (SERVER_ID, USER_ID),
  CONSTRAINT FK_SERVER_MEMBERS_SERVER
    FOREIGN KEY (SERVER_ID) REFERENCES SERVERS (SERVER_ID) ON DELETE CASCADE,
  CONSTRAINT FK_SERVER_MEMBERS_USER
    FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID) ON DELETE CASCADE
);

CREATE TABLE SERVER_JOIN_REQUESTS (
  REQUEST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SERVER_ID NUMBER NOT NULL,
  USER_ID NUMBER NOT NULL,
  REQUEST_MESSAGE VARCHAR2(250),
  STATUS VARCHAR2(10) DEFAULT 'PENDING' NOT NULL
    CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED')),
  REQUEST_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  REVIEWED_BY NUMBER,
  REVIEWED_AT TIMESTAMP,
  CONSTRAINT FK_JOIN_REQUEST_SERVER
    FOREIGN KEY (SERVER_ID) REFERENCES SERVERS (SERVER_ID) ON DELETE CASCADE,
  CONSTRAINT FK_JOIN_REQUEST_USER
    FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID) ON DELETE CASCADE,
  CONSTRAINT FK_JOIN_REQUEST_REVIEWER
    FOREIGN KEY (REVIEWED_BY) REFERENCES USERS (USER_ID)
);

CREATE TABLE CHANNELS (
  CHANNEL_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SERVER_ID NUMBER NOT NULL,
  CHANNEL_NAME VARCHAR2(80) NOT NULL,
  CHANNEL_TOPIC VARCHAR2(250),
  CREATED_BY NUMBER NOT NULL,
  POSITION NUMBER DEFAULT 1 NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_CHANNELS_SERVER
    FOREIGN KEY (SERVER_ID) REFERENCES SERVERS (SERVER_ID) ON DELETE CASCADE,
  CONSTRAINT FK_CHANNELS_CREATOR
    FOREIGN KEY (CREATED_BY) REFERENCES USERS (USER_ID),
  CONSTRAINT UK_CHANNEL_NAME UNIQUE (SERVER_ID, CHANNEL_NAME)
);

CREATE TABLE MESSAGES (
  MESSAGE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CHANNEL_ID NUMBER NOT NULL,
  USER_ID NUMBER NOT NULL,
  MESSAGE_TEXT CLOB,
  MESSAGE_TYPE VARCHAR2(10) DEFAULT 'TEXT' NOT NULL
    CHECK (MESSAGE_TYPE IN ('TEXT', 'MIXED', 'FILE')),
  IS_DELETED NUMBER(1) DEFAULT 0 NOT NULL
    CHECK (IS_DELETED IN (0, 1)),
  EDITED_AT TIMESTAMP,
  DELETED_AT TIMESTAMP,
  DELETED_BY NUMBER,
  SENT_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_MESSAGES_CHANNEL
    FOREIGN KEY (CHANNEL_ID) REFERENCES CHANNELS (CHANNEL_ID) ON DELETE CASCADE,
  CONSTRAINT FK_MESSAGES_USER
    FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID) ON DELETE CASCADE,
  CONSTRAINT FK_MESSAGES_DELETED_BY
    FOREIGN KEY (DELETED_BY) REFERENCES USERS (USER_ID)
);

CREATE TABLE ATTACHMENTS (
  ATTACHMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  MESSAGE_ID NUMBER NOT NULL,
  FILE_NAME VARCHAR2(255) NOT NULL,
  FILE_URL VARCHAR2(500) NOT NULL,
  FILE_TYPE VARCHAR2(10) NOT NULL
    CHECK (FILE_TYPE IN ('IMAGE', 'VIDEO', 'AUDIO', 'DOCUMENT')),
  MIME_TYPE VARCHAR2(120) NOT NULL,
  FILE_SIZE NUMBER NOT NULL,
  CONSTRAINT FK_ATTACHMENTS_MESSAGE
    FOREIGN KEY (MESSAGE_ID) REFERENCES MESSAGES (MESSAGE_ID) ON DELETE CASCADE
);

CREATE TABLE CHANNEL_READ_STATE (
  CHANNEL_ID NUMBER NOT NULL,
  USER_ID NUMBER NOT NULL,
  LAST_READ_MESSAGE_ID NUMBER,
  LAST_READ_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_CHANNEL_READ_STATE PRIMARY KEY (CHANNEL_ID, USER_ID),
  CONSTRAINT FK_CHANNEL_READ_STATE_CHANNEL
    FOREIGN KEY (CHANNEL_ID) REFERENCES CHANNELS (CHANNEL_ID) ON DELETE CASCADE,
  CONSTRAINT FK_CHANNEL_READ_STATE_USER
    FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID) ON DELETE CASCADE,
  CONSTRAINT FK_CHANNEL_READ_STATE_MESSAGE
    FOREIGN KEY (LAST_READ_MESSAGE_ID) REFERENCES MESSAGES (MESSAGE_ID)
);

CREATE INDEX IDX_SERVER_MEMBERS_USER ON SERVER_MEMBERS (USER_ID);
CREATE INDEX IDX_CHANNELS_SERVER ON CHANNELS (SERVER_ID);
CREATE INDEX IDX_MESSAGES_CHANNEL ON MESSAGES (CHANNEL_ID, SENT_AT);
CREATE INDEX IDX_JOIN_REQUESTS_SERVER ON SERVER_JOIN_REQUESTS (SERVER_ID, STATUS);
CREATE INDEX IDX_CHANNEL_READ_USER ON CHANNEL_READ_STATE (USER_ID, LAST_READ_AT);
